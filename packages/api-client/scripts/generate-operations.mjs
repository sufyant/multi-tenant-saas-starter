// Writes what Orval does not carry from the OpenAPI document (decision 10 in docs/frontend/ARCHITECTURE.md; D1):
// - src/generated/operations.gen.ts: each operation's id, method, path and the response headers it declares. The BFF reads it to
//   know which headers of an answer reach the browser.
// - src/generated/msw.gen.ts: one module that re-exports the MSW handlers of every tag. Orval writes one file per tag.
//
// Run it after Orval: `pnpm generate` in this package. It reads apps/api/openapi/v1.json and needs no dependency.
import { readFileSync, writeFileSync } from "node:fs";

const documentPath = "../../apps/api/openapi/v1.json";
const document = JSON.parse(
  readFileSync(new URL(documentPath, `file://${process.cwd()}/`), "utf8"),
);
const header = `// Generated by scripts/generate-operations.mjs from ${documentPath.replace("../../", "")}. Do not edit.\n// Run \`pnpm generate\` at the repository root.\n`;

const methods = ["get", "post", "put", "patch", "delete"];
const operations = [];
for (const [path, item] of Object.entries(document.paths)) {
  for (const method of methods) {
    const operation = item[method];
    if (!operation) continue;
    const names = new Set();
    for (const response of Object.values(operation.responses ?? {})) {
      for (const name of Object.keys(response.headers ?? {})) names.add(name);
    }
    operations.push({
      operationId: operation.operationId,
      method: method.toUpperCase(),
      path,
      tag: operation.tags[0],
      responseHeaders: [...names].sort(),
    });
  }
}
operations.sort((a, b) => a.operationId.localeCompare(b.operationId));

writeFileSync(
  "src/generated/operations.gen.ts",
  `${header}
export const operations = ${JSON.stringify(operations, null, 2)} as const;
`,
);

// Orval names a tag's folder after the tag in kebab case: Platform/AuditLogs becomes platform-auditlogs.
const folders = [
  ...new Set(
    operations.map((operation) =>
      operation.tag.toLowerCase().replace("/", "-"),
    ),
  ),
].sort();
writeFileSync(
  "src/generated/msw.gen.ts",
  `${header}
${folders.map((folder) => `export * from "./${folder}/${folder}.msw.gen";`).join("\n")}
`,
);
