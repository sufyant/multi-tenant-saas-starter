import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  colorLiterals,
  contractEnumValues,
  crossFeatureImports,
  dateFormattingOutsideFormatter,
  declarationsOf,
  differingFiles,
  duplicateRuleIds,
  enumLiterals,
  errorCodeMessages,
  generatedFileNames,
  messageKeySets,
  nativeChoiceControls,
  numericLayerClasses,
  physicalDirectionClasses,
  roleNameDecisions,
  sdkImportRefusals,
  testFolders,
  testsBesideTheirFile,
  userFacingLiterals,
} from "./architecture-rules";

// Each test writes a small folder and runs one rule on it, so a rule is proved to find what it must find.
function folder(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), "architecture-"));
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  return root;
}

describe("architecture rules", () => {
  it("PhysicalDirectionClasses_MarginLeftInATsxFile_IsAFinding", () => {
    const root = folder({
      "a.tsx": 'export const A = () => <div className="ml-4 ms-2" />;',
    });

    expect(physicalDirectionClasses(root)).toEqual([
      'a.tsx:1: physical direction class "ml-4"; use its logical form',
    ]);
  });

  it("PhysicalDirectionClasses_WordInAComment_IsNoFinding", () => {
    const root = folder({
      "a.tsx":
        "/** It mirrors in right-to-left. */\nexport const A = 1; // left-aligned",
    });

    expect(physicalDirectionClasses(root)).toEqual([]);
  });

  it("PhysicalDirectionClasses_LogicalClassesOnly_AreNoFinding", () => {
    const root = folder({
      "a.tsx":
        'export const A = () => <div className="ms-4 pe-2 start-0 text-start" />;',
    });

    expect(physicalDirectionClasses(root)).toEqual([]);
  });

  it("ColorLiterals_HexInACssFile_IsAFinding", () => {
    const root = folder({
      "a.css": ".a { color: #2747d8; }",
      "tokens.gen.css": ":root { --a: #2747d8; }",
    });

    expect(colorLiterals(root)).toEqual([
      'a.css:1: colour literal "#2747d8"; use a token',
    ]);
  });

  it("NumericLayerClasses_NumberAndArbitraryValue_AreFindings", () => {
    const root = folder({
      "a.tsx":
        'export const A = () => <div className="isolate z-50 data-open:z-[60]" />;',
    });

    expect(numericLayerClasses(root)).toEqual([
      'a.tsx:1: numeric layer class "z-50"; use a layer token',
      'a.tsx:1: numeric layer class "z-[60]"; use a layer token',
    ]);
  });

  it("NumericLayerClasses_LocalZ10AndLayerTokens_AreNoFinding", () => {
    const root = folder({
      "a.tsx":
        'export const A = () => <div className="z-10 focus:z-10 z-sticky z-popover" />;',
      "b.css": ".b { z-index: var(--z-dialog); }",
    });

    expect(numericLayerClasses(root)).toEqual([]);
  });

  it("UserFacingLiterals_JsxTextAndAriaLabel_AreFindings", () => {
    const root = folder({
      "a.tsx":
        'export const A = () => <button type="button" aria-label="Close">Save · {x}</button>;',
    });

    expect(userFacingLiterals(root)).toHaveLength(2);
  });

  it("UserFacingLiterals_PunctuationOnly_IsNoFinding", () => {
    const root = folder({ "a.tsx": "export const A = () => <span>·</span>;" });

    expect(userFacingLiterals(root)).toEqual([]);
  });

  it("TestFolders_TestsFolder_IsAFinding", () => {
    const root = folder({ "app/__tests__/a.test.ts": "" });

    expect(testFolders(root)).toHaveLength(1);
  });

  it("TestsBesideTheirFile_TestWithoutItsFile_IsAFinding", () => {
    const root = folder({
      "a.test.ts": "",
      "b.test.tsx": "",
      "b.tsx": "",
      "architecture.test.ts": "",
    });

    expect(testsBesideTheirFile(root)).toEqual([
      "a.test.ts: no file of the same base name beside the test",
    ]);
  });

  it("CrossFeatureImports_FeatureImportsAnother_IsAFinding", () => {
    const root = folder({
      "features/shell/a.ts":
        'import { b } from "@/features/members/b";\nimport { c } from "./c";',
      "features/shell/c.ts": "",
      "features/members/b.ts": "",
    });

    expect(crossFeatureImports(root)).toEqual([
      "features/shell/a.ts:1: feature shell imports feature members",
    ]);
  });

  it("GeneratedFileNames_GeneratedFileWithoutGen_IsAFinding", () => {
    const root = folder({
      "a.ts": "/**\n * Generated by orval\n * Do not edit manually.\n */",
      "b.gen.ts": "",
    });

    expect(generatedFileNames(root)).toHaveLength(1);
  });

  it("MessageKeySets_KeyMissingInOneLanguage_IsAFinding", () => {
    const root = folder({
      "en.json":
        '{ "members": { "invite": "Invite member", "title": "Members" } }',
      "tr.json":
        '{ "members": { "invite": "Üye davet et", "title": "Üyeler" } }',
      "ar.json": '{ "members": { "invite": "دعوة عضو" } }',
    });

    expect(messageKeySets(root, ["en", "tr", "ar"])).toEqual([
      "ar.json: no key members.title",
    ]);
  });

  it("ErrorCodeMessages_CodeWithoutMessage_IsAFinding", () => {
    const root = folder({
      "en.json": '{ "errors": { "tenant": { "not_found": "Not found" } } }',
    });

    expect(
      errorCodeMessages(root, ["en"], ["tenant.not_found", "tenant.closed"]),
    ).toEqual(["en.json: no key errors.tenant.closed"]);
  });

  it("DateFormattingOutsideFormatter_IntlDateTimeFormat_IsAFinding", () => {
    const root = folder({
      "a.ts": "export const a = new Intl.DateTimeFormat();",
      "format-date-time.ts": "export const b = new Intl.DateTimeFormat();",
    });

    expect(dateFormattingOutsideFormatter(root)).toHaveLength(1);
  });

  it("EnumLiterals_ValueAsALiteral_IsAFinding", () => {
    const root = folder({
      "a.ts":
        'export const a = "tenant.not_found";\nexport const b = "errors.tenant.not_found";',
      "a.test.ts": 'export const c = "tenant.not_found";',
    });

    expect(enumLiterals(root, new Set(["tenant.not_found"]))).toEqual([
      'a.ts:1: enum value "tenant.not_found" as a literal',
    ]);
  });

  it("EnumLiterals_LiteralType_IsNoFinding", () => {
    const root = folder({
      "a.tsx": 'export const A = (props: React.ComponentProps<"tr">) => props;',
    });

    expect(enumLiterals(root, new Set(["tr"]))).toEqual([]);
  });

  it("RoleNameDecisions_ComparisonOfARolesName_IsAFinding", () => {
    const root = folder({
      "a.ts": [
        'export const a = (role: R) => role.name === "owner";',
        "export const b = (m: M) => m.role.name !== BuiltInRole.Admin;",
        "export const c = (role: R) => builtInRoleOf(role) === BuiltInRole.Owner;",
        "export const d = (role: R) => { switch (role.name) { default: return 0; } };",
        'export const e = (role: R) => roleSelect(role) === "owner";',
      ].join("\n"),
    });

    expect(roleNameDecisions(root)).toEqual([
      "a.ts:1: compares a role's name; decide by its permissions (F51)",
      "a.ts:2: compares a role's name; decide by its permissions (F51)",
      "a.ts:3: compares a role's name; decide by its permissions (F51)",
      "a.ts:4: compares a role's name; decide by its permissions (F51)",
      "a.ts:5: compares a role's name; decide by its permissions (F51)",
    ]);
  });

  it("RoleNameDecisions_ImportOfBuiltInRoleOf_IsAFinding", () => {
    const root = folder({
      "a.ts": 'import { builtInRoleOf } from "@/shared/roles";',
    });

    expect(roleNameDecisions(root)).toEqual([
      "a.ts:1: imports builtInRoleOf; a role's name is only its text (F51)",
    ]);
  });

  it("RoleNameDecisions_IgnoredFileAndOtherNames_AreNoFinding", () => {
    const root = folder({
      "shared/roles.ts": 'export const a = (role: R) => role.name === "owner";',
      "b.ts": [
        "export const b = (person: P) => person.name === other.name;",
        "export const c = (role: R) => role.id === roleId;",
        "export const d = (role: R) => role.name;",
      ].join("\n"),
    });

    expect(roleNameDecisions(root, { ignore: ["shared/roles.ts"] })).toEqual(
      [],
    );
  });

  it("DeclarationsOf_OwnCopyOfAName_IsAFinding", () => {
    const root = folder({
      "shared/roles.ts": [
        'export const BuiltInRole = { Owner: "owner" } as const;',
        "export type BuiltInRole = string;",
        "export function builtInRoleOf() { return null; }",
      ].join("\n"),
    });

    expect(declarationsOf(root, ["BuiltInRole", "builtInRoleOf"])).toEqual([
      "shared/roles.ts:1: declares BuiltInRole; import it from @repo/api-client (F3)",
      "shared/roles.ts:2: declares BuiltInRole; import it from @repo/api-client (F3)",
      "shared/roles.ts:3: declares builtInRoleOf; import it from @repo/api-client (F3)",
    ]);
  });

  it("DeclarationsOf_ImportAndOtherNames_AreNoFinding", () => {
    const root = folder({
      "a.ts": [
        'import { BuiltInRole, builtInRoleOf } from "@repo/api-client";',
        "export const inListOrder = () => [BuiltInRole, builtInRoleOf];",
      ].join("\n"),
    });

    expect(declarationsOf(root, ["BuiltInRole", "builtInRoleOf"])).toEqual([]);
  });

  it("DeclarationsOf_AnotherSource_NamesItsPackageAndItsRule", () => {
    const root = folder({
      "shared/list-error.tsx": "export function ListError() { return null; }",
    });

    expect(
      declarationsOf(root, ["ListError"], {
        from: "@repo/ui",
        rule: "F29",
      }),
    ).toEqual([
      "shared/list-error.tsx:1: declares ListError; import it from @repo/ui (F29)",
    ]);
  });

  it("NativeChoiceControls_CheckboxAndRadioInputs_AreFindings", () => {
    const root = folder({
      "a.tsx": [
        'export const A = () => <input type="checkbox" />;',
        'export const B = () => <input type={"radio"} />;',
      ].join("\n"),
    });

    expect(nativeChoiceControls(root)).toEqual([
      'a.tsx:1: a native type="checkbox"; use Checkbox or RadioGroup of @repo/ui (F52)',
      'a.tsx:2: a native type="radio"; use Checkbox or RadioGroup of @repo/ui (F52)',
    ]);
  });

  it("NativeChoiceControls_OtherTypesAndTests_AreNoFinding", () => {
    const root = folder({
      "a.tsx": 'export const A = () => <input type="search" />;',
      "a.test.tsx": 'render(<input type="checkbox" />);',
    });

    expect(nativeChoiceControls(root)).toEqual([]);
  });

  it("ContractEnumValues_GeneratedFile_ReadsEveryEnumButSortsAndKinds", () => {
    const root = folder({
      "schemas.gen.ts": [
        "export const Language = {\n  en: 'en',\n  tr: 'tr',\n} as const;",
        "export const ListMembersSort = {\n  email: 'email',\n} as const;",
        "export const InviterNameResponseKind = {\n  user: 'user',\n} as const;",
      ].join("\n"),
    });

    expect([...contractEnumValues(join(root, "schemas.gen.ts"))]).toEqual([
      "en",
      "tr",
    ]);
  });

  it("DuplicateRuleIds_TwoRowsWithOneId_IsAFinding", () => {
    const root = folder({
      "ARCHITECTURE.md":
        "| Id | Rule |\n| --- | --- |\n| F1 | One |\n| F2 | Two |\n| F1 | Three |\n",
    });

    expect(duplicateRuleIds(join(root, "ARCHITECTURE.md"))).toEqual([
      "ARCHITECTURE.md:3: rule id F1 is on lines 3, 5; give each rule its own id",
      "ARCHITECTURE.md:5: rule id F1 is on lines 3, 5; give each rule its own id",
    ]);
  });

  it("DuplicateRuleIds_DistinctIds_AreNoFinding", () => {
    const root = folder({
      "ARCHITECTURE.md":
        "| Id | Rule |\n| --- | --- |\n| F1 | One, as F2 says |\n| F2 | Two |\n",
    });

    expect(duplicateRuleIds(join(root, "ARCHITECTURE.md"))).toEqual([]);
  });

  it("DifferingFiles_FileInOneFolderOnly_IsAFinding", () => {
    const root = folder({
      "a/options.ts": "x",
      "a/extra.ts": "y",
      "b/options.ts": "x",
    });

    expect(differingFiles(join(root, "a"), join(root, "b"))).toEqual([
      "extra.ts: in one folder only; keep both copies the same",
    ]);
  });

  it("DifferingFiles_ChangedCopy_IsAFinding", () => {
    const root = folder({ "a/options.ts": "x", "b/options.ts": "z" });

    expect(differingFiles(join(root, "a"), join(root, "b"))).toEqual([
      "options.ts: the two copies differ; keep them the same",
    ]);
  });

  it("DifferingFiles_SameCopies_AreNoFinding", () => {
    const root = folder({ "a/options.ts": "x", "b/options.ts": "x" });

    expect(differingFiles(join(root, "a"), join(root, "b"))).toEqual([]);
  });

  // The rule lints probe files with the repository's own biome.json.
  it("SdkImportRefusals_FeatureAndErrorTrackingFolder_RefusesTheFeatureOnly", () => {
    expect(
      sdkImportRefusals(join(import.meta.dirname, "../../.."), [
        "apps/web/src/error-tracking/probe.ts",
        "apps/web/src/features/probe/probe.ts",
      ]),
    ).toEqual(["apps/web/src/features/probe/probe.ts"]);
  });
});
