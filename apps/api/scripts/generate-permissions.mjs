// Writes the permission list of ControlPlane.Contracts from the one source of the permission names, ControlPlane.Domain's
// PermissionPools with the product's ProductPermissions (D1, X1). Contracts never references Domain (section 2), so it reads a generated copy, and CI fails when the copy
// differs from what this script writes (scripts/ci/check-generated.sh). Run it from apps/api: node scripts/generate-permissions.mjs
import { readFileSync, writeFileSync } from "node:fs";

const sources = ["src/Modules/ControlPlane/ControlPlane.Domain/PermissionPools.cs", "src/Modules/ControlPlane/ControlPlane.Domain/ProductPermissions.cs"];
const output = "src/Modules/ControlPlane/ControlPlane.Contracts/Permissions.g.cs";

const constants = sources.flatMap((source) => [...readFileSync(source, "utf8").matchAll(/^ {4}public const string (\w+) = ("[^"]+");$/gm)]);
if (constants.length === 0) {
  throw new Error(`${sources[0]} declares no permission.`);
}

const lines = [
  "// <auto-generated/>",
  `// Written by apps/api/scripts/generate-permissions.mjs from ${sources[0].replace("src/Modules/ControlPlane/", "")}. Do not edit it: run`,
  "// `pnpm generate`.",
  "namespace ControlPlane.Contracts;",
  "",
  "/// <summary>",
  "/// The permission list. Permissions are fixed in code, each tied to a capability. Endpoints name a permission as their",
  "/// authorization policy (A1).",
  "/// </summary>",
  "public static class Permissions",
  "{",
  constants.map(([, name, value]) => `    public const string ${name} = ${value};`).join("\n\n"),
  "}",
  "",
];

writeFileSync(output, lines.join("\n"));
