// Writes the keys of the feature flags that the code defines from their one source, ControlPlane.Domain's FeatureFlagKeys (D1): a copy
// in ControlPlane.Contracts, which any module reads to ask IFeatureFlags, and one for the web in packages/api-client, whose hook takes a
// key of the list. Contracts never references Domain (section 2), so it reads the generated copy, and CI fails when a copy differs from
// what this script writes (scripts/ci/check-generated.sh). A catalog without a flag writes empty lists. Run it from apps/api:
// node scripts/generate-feature-flags.mjs
import { readFileSync, writeFileSync } from "node:fs";

const folder = "src/Modules/ControlPlane";
const source = "ControlPlane.Domain/FeatureFlags/FeatureFlagKeys.cs";
const constants = [...readFileSync(`${folder}/${source}`, "utf8").matchAll(/^ {4}public const string (\w+) = ("[^"]+");$/gm)];

writeFileSync(
  `${folder}/ControlPlane.Contracts/FeatureFlags/FeatureFlagKeys.g.cs`,
  [
    "// <auto-generated/>",
    `// Written by apps/api/scripts/generate-feature-flags.mjs from ${source}. Do not edit it: run \`pnpm generate\`.`,
    "namespace ControlPlane.Contracts.FeatureFlags;",
    "",
    "/// <summary>The keys of the feature flags that the code defines, which a module asks IFeatureFlags about (docs/flows/feature-flags.md).</summary>",
    "public static class FeatureFlagKeys",
    "{",
    constants.map(([, name, value]) => `    public const string ${name} = ${value};`).join("\n\n"),
    "}",
    "",
  ]
    .join("\n")
    .replace("{\n\n}", "{\n}"),
);

writeFileSync(
  "../../packages/api-client/src/feature-flags.gen.ts",
  [
    `// Written by apps/api/scripts/generate-feature-flags.mjs from apps/api/src/Modules/ControlPlane/${source}. Do not edit it: run \`pnpm generate\`.`,
    "",
    "/** The keys of the feature flags that the code defines (apps/api/docs/flows/feature-flags.md). */",
    constants.length === 0 ? "export const FeatureFlagKeys = [] as const;" : ["export const FeatureFlagKeys = [", ...constants.map(([, , value]) => `  ${value},`), "] as const;"].join("\n"),
    "",
    "export type FeatureFlagKey = (typeof FeatureFlagKeys)[number];",
    "",
  ].join("\n"),
);
